public class Ejercicio4 {
    public static void main(String[] args) {
        // TODO: Imprimir números del 1 al 20 usando bucle 'for'
        System.out.println("Números del 1 al 20 con 'for': ");
        for (int i = 1; i <= 20; i++) {
            System.out.print(i + " ");
        }
        System.out.println();

        // TODO: Imprimir números del 20 al 1 usando bucle 'while'
        System.out.println("Números del 20 al 1 con 'while':");
        int j = 20;
        while (j >= 1) {
            System.out.print(j + " ");
            j--;
        }
        System.out.println();
    }
}
