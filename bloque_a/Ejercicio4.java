public class Ejercicio4 {
    public static void main(String[] args) {
        // TODO: Imprimir números del 1 al 20 usando bucle 'for'
        System.out.println("--- Bucle For Incremental (1 al 20) ---");
        for (int i = 1; i <= 20; i++) {
            system.out.println(i);
        }

        // TODO: Imprimir números del 20 al 1 usando bucle 'while'
        System.out.println("--- Bucle While Decremental (20 al 1) ---");
        int j = 20;
        while (j >= 1) {
            System.out.println(j);
            j--;
        }
    }
}
