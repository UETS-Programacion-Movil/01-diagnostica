public class Ejercicio3 {
    public static void main(String[] args) {
        System.out.println("Bucle for del 1 al 5:");
        for (int i = 1; i <= 5; i++) {
            System.out.println("Número: " + i);
        }

        System.out.println("Bucle while del 5 al 1:");
        int j = 5;
        while (j >= 1) {
            System.out.println("Número: " + j);
            j--;
        }
    }
}